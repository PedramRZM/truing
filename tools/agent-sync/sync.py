#!/usr/bin/env python3
"""Generate per-harness agent configuration from the canonical, harness-neutral sources.

Canonical sources (edit these):
  AGENTS.md                 instructions for every harness (CLAUDE.md only imports it)
  .agents/skills/<name>/    Agent Skills (SKILL.md with portable frontmatter only)
  .mcp.json                 MCP servers (Claude Code / VS Code / Copilot CLI format)

Generated glue (never edit by hand; `make sync` rewrites it, `make check` fails on drift):
  .claude/skills/<name>     symlinks into .agents/skills (Claude Code doesn't read .agents/)
  .codex/config.toml        Codex MCP servers
  .gemini/settings.json     Gemini CLI: AGENTS.md as context file + MCP servers
  .agents/mcp_config.json   Antigravity MCP servers
  opencode.json             OpenCode MCP servers
  .cursor/mcp.json          Cursor MCP servers
  .vscode/mcp.json          VS Code / GitHub Copilot MCP servers

Usage: sync.py [--check]
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SKILLS_DIR = ROOT / ".agents" / "skills"
CLAUDE_SKILLS_DIR = ROOT / ".claude" / "skills"
MCP_SOURCE = ROOT / ".mcp.json"

GENERATED_HEADER = "Generated by tools/agent-sync/sync.py from .mcp.json - edit .mcp.json, then run `make sync`."
SKILL_NAME = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
PORTABLE_SKILL_KEYS = {"name", "description", "license", "compatibility", "metadata", "allowed-tools"}
AGENTS_MD_MAX_LINES = 150
AGENTS_MD_MAX_BYTES = 24_000  # Antigravity's per-file cap; Codex caps the whole chain at 32 KiB
SKILL_MAX_LINES = 500
DESCRIPTION_MAX_CHARS = 1024


class Problems:
    def __init__(self) -> None:
        self.errors: list[str] = []
        self.drift: list[str] = []

    def error(self, message: str) -> None:
        self.errors.append(message)


# ---------------------------------------------------------------- skills


def parse_frontmatter(text: str) -> dict[str, str] | None:
    """Minimal YAML-frontmatter reader: top-level `key: value` lines; indented lines continue the previous key."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return None
    fields: dict[str, str] = {}
    current = None
    for line in lines[1:]:
        if line.strip() == "---":
            return fields
        match = re.match(r"^([A-Za-z0-9_-]+):(.*)$", line)
        if match and not line.startswith((" ", "\t")):
            current = match.group(1)
            fields[current] = match.group(2).strip().strip("'\"")
        elif current and line.strip():
            fields[current] = (fields[current] + " " + line.strip()).strip()
    return None  # no closing ---


def validate_skills(problems: Problems) -> list[str]:
    if not SKILLS_DIR.is_dir():
        problems.error(f"{SKILLS_DIR.relative_to(ROOT)} is missing")
        return []
    names = []
    for skill_dir in sorted(p for p in SKILLS_DIR.iterdir() if p.is_dir()):
        rel = skill_dir.relative_to(ROOT)
        skill_file = skill_dir / "SKILL.md"
        if not skill_file.is_file():
            problems.error(f"{rel}: missing SKILL.md")
            continue
        text = skill_file.read_text(encoding="utf-8")
        fields = parse_frontmatter(text)
        if fields is None:
            problems.error(f"{rel}/SKILL.md: frontmatter must start and end with '---'")
            continue
        name = fields.get("name", "")
        if name != skill_dir.name:
            problems.error(f"{rel}/SKILL.md: name '{name}' must equal the folder name '{skill_dir.name}'")
        if not SKILL_NAME.match(skill_dir.name) or len(skill_dir.name) > 64:
            problems.error(f"{rel}: folder name must be lowercase-hyphenated and at most 64 characters")
        description = fields.get("description", "")
        if not description:
            problems.error(f"{rel}/SKILL.md: description is required (it is how agents decide to use the skill)")
        elif len(description) > DESCRIPTION_MAX_CHARS:
            problems.error(f"{rel}/SKILL.md: description is {len(description)} chars; the spec allows {DESCRIPTION_MAX_CHARS}")
        extra = sorted(set(fields) - PORTABLE_SKILL_KEYS)
        if extra:
            problems.error(
                f"{rel}/SKILL.md: non-portable frontmatter keys {extra}; keep to {sorted(PORTABLE_SKILL_KEYS)} "
                "so every harness can load the skill"
            )
        line_count = len(text.splitlines())
        if line_count >= SKILL_MAX_LINES:
            problems.error(f"{rel}/SKILL.md: {line_count} lines; move detail into references/ (limit {SKILL_MAX_LINES})")
        names.append(skill_dir.name)
    return names


def sync_claude_skill_links(names: list[str], check: bool, problems: Problems) -> None:
    if not check:
        CLAUDE_SKILLS_DIR.mkdir(parents=True, exist_ok=True)
    wanted = {name: Path("..", "..", ".agents", "skills", name) for name in names}
    for name, target in wanted.items():
        link = CLAUDE_SKILLS_DIR / name
        rel = link.relative_to(ROOT)
        if link.is_symlink():
            if Path(os.readlink(link)) == target:
                continue
            problems.drift.append(f"{rel} points to {os.readlink(link)}, expected {target}")
            if not check:
                link.unlink()
                link.symlink_to(target, target_is_directory=True)
        elif link.exists():
            problems.error(f"{rel} is a real directory; move it to .agents/skills/{name} and run `make sync`")
        else:
            problems.drift.append(f"{rel} symlink is missing")
            if not check:
                link.symlink_to(target, target_is_directory=True)
    if CLAUDE_SKILLS_DIR.is_dir():
        for link in CLAUDE_SKILLS_DIR.iterdir():
            if link.is_symlink() and link.name not in wanted:
                problems.drift.append(f"{link.relative_to(ROOT)} is a stale symlink")
                if not check:
                    link.unlink()


# ---------------------------------------------------------------- MCP


def load_mcp_servers(problems: Problems) -> dict[str, dict]:
    if not MCP_SOURCE.is_file():
        return {}
    raw = MCP_SOURCE.read_text(encoding="utf-8")
    if "${" in raw:
        problems.error(
            ".mcp.json uses ${VAR} expansion; each harness expands secrets differently. "
            "Extend tools/agent-sync/sync.py to translate it before adding such a server."
        )
    servers = json.loads(raw).get("mcpServers", {})
    for name, cfg in servers.items():
        kind = server_kind(cfg)
        if kind is None:
            problems.error(f".mcp.json: server '{name}' needs either 'url' (remote) or 'command' (stdio)")
        if kind == "remote" and cfg.get("headers"):
            problems.error(f".mcp.json: server '{name}' uses headers, which the generator doesn't translate yet")
    return servers


def server_kind(cfg: dict) -> str | None:
    if cfg.get("url"):
        return "remote"
    if cfg.get("command"):
        return "stdio"
    return None


def stdio_fields(cfg: dict) -> dict:
    out = {"command": cfg["command"]}
    if cfg.get("args"):
        out["args"] = list(cfg["args"])
    if cfg.get("env"):
        out["env"] = dict(cfg["env"])
    return out


def render_json(data: dict) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def cursor_mcp(servers: dict) -> str:
    return render_json({"mcpServers": servers})


def vscode_mcp(servers: dict) -> str:
    out = {}
    for name, cfg in servers.items():
        if server_kind(cfg) == "remote":
            out[name] = {"type": "sse" if cfg.get("type") == "sse" else "http", "url": cfg["url"]}
        else:
            out[name] = {"type": "stdio", **stdio_fields(cfg)}
    return render_json({"servers": out})


def gemini_settings(servers: dict) -> str:
    out = {}
    for name, cfg in servers.items():
        if server_kind(cfg) == "remote":
            out[name] = {"url": cfg["url"]} if cfg.get("type") == "sse" else {"httpUrl": cfg["url"]}
        else:
            out[name] = stdio_fields(cfg)
    return render_json({"context": {"fileName": ["AGENTS.md"]}, "mcpServers": out})


def antigravity_mcp(servers: dict) -> str:
    out = {}
    for name, cfg in servers.items():
        out[name] = {"serverUrl": cfg["url"]} if server_kind(cfg) == "remote" else stdio_fields(cfg)
    return render_json({"mcpServers": out})


def opencode_config(servers: dict) -> str:
    out = {}
    for name, cfg in servers.items():
        if server_kind(cfg) == "remote":
            out[name] = {"type": "remote", "url": cfg["url"], "enabled": True}
        else:
            entry = {"type": "local", "command": [cfg["command"], *cfg.get("args", [])], "enabled": True}
            if cfg.get("env"):
                entry["environment"] = dict(cfg["env"])
            out[name] = entry
    return render_json({"$schema": "https://opencode.ai/config.json", "mcp": out})


def toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)  # JSON string escapes are valid TOML basic strings


def codex_config(servers: dict) -> str:
    lines = [f"# {GENERATED_HEADER}", "# Codex loads project config only for trusted projects.", ""]
    for name, cfg in servers.items():
        lines.append(f"[mcp_servers.{name}]")
        if server_kind(cfg) == "remote":
            lines.append(f"url = {toml_string(cfg['url'])}")
        else:
            lines.append(f"command = {toml_string(cfg['command'])}")
            if cfg.get("args"):
                lines.append("args = [" + ", ".join(toml_string(a) for a in cfg["args"]) + "]")
            if cfg.get("env"):
                lines.append(f"[mcp_servers.{name}.env]")
                lines.extend(f"{key} = {toml_string(val)}" for key, val in cfg["env"].items())
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


GENERATORS = {
    ".cursor/mcp.json": cursor_mcp,
    ".vscode/mcp.json": vscode_mcp,
    ".gemini/settings.json": gemini_settings,
    ".agents/mcp_config.json": antigravity_mcp,
    "opencode.json": opencode_config,
    ".codex/config.toml": codex_config,
}


def sync_generated_files(servers: dict, check: bool, problems: Problems) -> None:
    for rel, generator in GENERATORS.items():
        path = ROOT / rel
        wanted = generator(servers)
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == wanted:
            continue
        problems.drift.append(f"{rel} is {'missing' if current is None else 'out of date'}")
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(wanted, encoding="utf-8")


# ---------------------------------------------------------------- instructions


def check_instructions(problems: Problems) -> None:
    agents = ROOT / "AGENTS.md"
    if not agents.is_file():
        problems.error("AGENTS.md is missing")
        return
    data = agents.read_bytes()
    lines = data.decode("utf-8").count("\n")
    if lines > AGENTS_MD_MAX_LINES:
        problems.error(f"AGENTS.md has {lines} lines (budget {AGENTS_MD_MAX_LINES}); move detail into docs/ and link to it")
    if len(data) > AGENTS_MD_MAX_BYTES:
        problems.error(f"AGENTS.md is {len(data)} bytes (Antigravity reads at most {AGENTS_MD_MAX_BYTES})")
    claude = ROOT / "CLAUDE.md"
    if not claude.is_file() or "@AGENTS.md" not in claude.read_text(encoding="utf-8"):
        problems.error("CLAUDE.md must import @AGENTS.md so Claude Code reads the shared instructions")
    if (ROOT / "GEMINI.md").exists():
        problems.error("GEMINI.md would duplicate AGENTS.md (Gemini CLI is pointed at AGENTS.md via .gemini/settings.json)")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report drift and problems without writing")
    args = parser.parse_args()

    problems = Problems()
    check_instructions(problems)
    names = validate_skills(problems)
    try:
        sync_claude_skill_links(names, args.check, problems)
        sync_generated_files(load_mcp_servers(problems), args.check, problems)
    except PermissionError as exc:
        print(
            f"error: cannot write {exc.filename}: permission denied.\n"
            "Claude Code's sandbox protects .claude/ from shell writes so agents can't install skills silently.\n"
            "Run `make sync` from your own terminal, or approve running it outside the sandbox.",
            file=sys.stderr,
        )
        return 1

    for message in problems.errors:
        print(f"error: {message}", file=sys.stderr)
    if args.check:
        for message in problems.drift:
            print(f"drift: {message} (run `make sync`)", file=sys.stderr)
        ok = not problems.errors and not problems.drift
        print(f"agent-sync: {'ok' if ok else 'FAILED'} ({len(names)} skills, {len(GENERATORS)} generated files)")
        return 0 if ok else 1
    for message in problems.drift:
        print(f"updated: {message}")
    print(f"agent-sync: {'ok' if not problems.errors else 'FAILED'} ({len(names)} skills)")
    return 0 if not problems.errors else 1


if __name__ == "__main__":
    sys.exit(main())
